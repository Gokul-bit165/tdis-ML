/**
 * @fileoverview Shared Flood Hub UI: overlay switch + riverine floods block (main HMED panel).
 */

import React, { useState } from 'react';
import PropTypes from 'prop-types';
import * as Dialog from '@radix-ui/react-dialog';
import { Info, Waves } from 'lucide-react';
import { cn } from '@/lib/utils';
import { trackLayerToggle } from '../../utils/googleAnalytics.js';
import CustomTooltip from '../ui/CustomTooltip';

/** Expected severity for riverine gauge hexes (informational; aligns with map tiers). */
export const RIVERINE_SEVERITY_LEGEND = [
  { label: 'Extreme', color: '#7f1d1d' },
  { label: 'Danger', color: '#dc2626' },
  { label: 'Warning', color: '#ea580c' },
  { label: 'No data', color: '#94a3b8' },
  { label: 'Normal', color: '#22c55e' },
];

/** Matches the glossary copy in the gauge side panel. */
export const RIVERINE_LOWER_CONFIDENCE_HELP =
  "By default, you only see data from gauges that meet Google's high-confidence threshold. Select this option to include data from gauges with lower-confidence, giving you a more complete picture.";

export const LOWER_CONFIDENCE_DISCLAIMER_TITLE =
  'This information may be less accurate, and intended for expert and research use only';

export const LOWER_CONFIDENCE_DISCLAIMER_BODY =
  "The quality of forecasts shown in this view varies. While all forecasts in the Flood Hub are generated by Google's flood forecasting model, the predictions for the lower-confidence gauges might be less accurate. This means that either the data necessary for evaluation was unavailable, or the evaluation did not meet our performance standards.";

export const LOWER_CONFIDENCE_DISCLAIMER_CAUTION = 'Please use these forecasts with caution!';

/**
 * Disclaimer shown before enabling lower-confidence gauges.
 */
export function LowerConfidenceGaugesDisclaimerDialog({ open, onCancel, onAccept }) {
  return (
    <Dialog.Root
      open={open}
      onOpenChange={(next) => {
        if (!next) onCancel();
      }}
    >
      <Dialog.Portal>
        <Dialog.Overlay
          className={cn(
            'fixed inset-0 z-[200] bg-black/45',
            'data-[state=open]:animate-in data-[state=closed]:animate-out',
            'data-[state=closed]:fade-out-0 data-[state=open]:fade-in-0'
          )}
        />
        <Dialog.Content
          className={cn(
            'fixed left-1/2 top-1/2 z-[201] w-[min(92vw,440px)]',
            '-translate-x-1/2 -translate-y-1/2 rounded-xl bg-white p-6 shadow-xl',
            'outline-none focus:outline-none',
            'data-[state=open]:animate-in data-[state=closed]:animate-out',
            'data-[state=closed]:fade-out-0 data-[state=open]:fade-in-0',
            'data-[state=closed]:zoom-out-95 data-[state=open]:zoom-in-95'
          )}
        >
          <Dialog.Title className="text-base font-bold leading-snug tracking-tight text-slate-900">
            {LOWER_CONFIDENCE_DISCLAIMER_TITLE}
          </Dialog.Title>
          <Dialog.Description asChild>
            <div className="mt-3 space-y-3 text-sm leading-relaxed text-slate-600">
              <p>{LOWER_CONFIDENCE_DISCLAIMER_BODY}</p>
              <p>{LOWER_CONFIDENCE_DISCLAIMER_CAUTION}</p>
            </div>
          </Dialog.Description>
          <div className="mt-6 flex flex-wrap justify-end gap-1">
            <button
              type="button"
              className="rounded px-4 py-2 text-sm font-medium text-slate-700 hover:bg-slate-50"
              onClick={onCancel}
            >
              Cancel
            </button>
            <button
              type="button"
              className="rounded bg-blue-600 px-4 py-2 text-sm font-medium text-white hover:bg-blue-700"
              onClick={onAccept}
            >
              I accept
            </button>
          </div>
        </Dialog.Content>
      </Dialog.Portal>
    </Dialog.Root>
  );
}

LowerConfidenceGaugesDisclaimerDialog.propTypes = {
  open: PropTypes.bool.isRequired,
  onCancel: PropTypes.func.isRequired,
  onAccept: PropTypes.func.isRequired,
};

export function FloodHubOverlaySwitch({
  checked,
  onChange,
  disabled,
  labelledBy,
  ariaLabel,
  trackAnalytics = true,
}) {
  return (
    <button
      type="button"
      role="switch"
      aria-checked={checked}
      aria-label={ariaLabel || undefined}
      aria-labelledby={ariaLabel ? undefined : labelledBy}
      disabled={disabled}
      onClick={() => {
        if (disabled) return;
        const next = !checked;
        if (trackAnalytics) {
          trackLayerToggle({
            layer_name: ariaLabel || labelledBy || 'flood_hub_overlay',
            on: next,
            tab: 'hmed',
          });
        }
        onChange(next);
      }}
      className={[
        'relative h-7 w-12 shrink-0 rounded-full transition-colors focus:outline-none focus-visible:ring-2 focus-visible:ring-sky-500 focus-visible:ring-offset-1',
        disabled ? 'cursor-not-allowed opacity-50' : 'cursor-pointer',
        checked ? 'bg-sky-500' : 'bg-slate-200',
      ].join(' ')}
    >
      <span
        aria-hidden
        className={[
          'absolute top-1 h-5 w-5 rounded-full bg-white shadow-md transition-[left] duration-200 ease-out',
          checked ? 'left-6' : 'left-1',
        ].join(' ')}
      />
    </button>
  );
}

FloodHubOverlaySwitch.propTypes = {
  checked: PropTypes.bool.isRequired,
  onChange: PropTypes.func.isRequired,
  disabled: PropTypes.bool,
  labelledBy: PropTypes.string,
  ariaLabel: PropTypes.string,
  trackAnalytics: PropTypes.bool,
};

/**
 * Riverine / gauge hex controls for the main HMED panel (left sheet on desktop, controls drawer on mobile).
 * @param {object} props
 * @param {object} props.toggles
 * @param {Function} props.setToggles - (patch: object) => void
 */
export function FloodHubRiverineSection({ toggles, setToggles }) {
  const floodsLabelId = 'flood-hub-main-floods';
  const lowerConfidenceLabelId = 'flood-hub-main-lower-confidence';
  const [showLowerConfidenceDisclaimer, setShowLowerConfidenceDisclaimer] = useState(false);

  const handleLowerConfidenceChange = (next) => {
    if (next) {
      setShowLowerConfidenceDisclaimer(true);
      return;
    }
    trackLayerToggle({
      layer_name: 'Lower-confidence gauges only',
      on: false,
      tab: 'hmed',
    });
    setToggles({ riverineLowerConfidenceOnly: false });
  };

  const handleDisclaimerCancel = () => {
    setShowLowerConfidenceDisclaimer(false);
  };

  const handleDisclaimerAccept = () => {
    setShowLowerConfidenceDisclaimer(false);
    setToggles({ riverineLowerConfidenceOnly: true });
    trackLayerToggle({
      layer_name: 'Lower-confidence gauges only',
      on: true,
      tab: 'hmed',
    });
  };

  return (
    <div className="mb-4 rounded-lg border border-sky-100 bg-sky-50/40 px-3 py-2.5">
      <p className="text-[10px] font-bold uppercase tracking-wide text-sky-950 mb-2">
        Riverine floods
      </p>
      <div className="space-y-2 border-t border-sky-100/80 pt-2">
        <div className="flex items-center gap-3 py-1">
          <Waves className="h-4 w-4 shrink-0 text-sky-600" strokeWidth={2} aria-hidden />
          <span
            id={floodsLabelId}
            className="min-w-0 flex-1 text-[11px] font-semibold text-slate-800"
          >
            Floods (riverine)
          </span>
          <FloodHubOverlaySwitch
            checked={!!toggles.gauges}
            labelledBy={floodsLabelId}
            onChange={(v) => setToggles({ gauges: v })}
          />
        </div>
        {toggles.gauges ? (
          <div
            className="rounded-lg border border-slate-200/90 bg-slate-100/90 px-3 py-2.5 shadow-inner"
            role="region"
            aria-label="Riverine floods severity"
          >
            <p className="text-[11px] font-bold text-slate-900">Riverine floods</p>
            <p className="text-[10px] text-slate-600 mt-0.5 mb-2">Expected severity</p>
            <ul className="space-y-2">
              {RIVERINE_SEVERITY_LEGEND.map(({ label, color }) => (
                <li key={label}>
                  {label === 'Normal' ? (
                    <div className="flex items-center justify-between gap-2">
                      <div className="flex min-w-0 items-center gap-2.5 text-[11px] text-slate-700">
                        <span
                          className="h-3 w-3 shrink-0 rounded-full border border-slate-300/60"
                          style={{ backgroundColor: color }}
                          aria-hidden
                        />
                        <span className="font-medium">{label}</span>
                      </div>
                      <FloodHubOverlaySwitch
                        checked={toggles.riverineShowNormal !== false}
                        ariaLabel="Show riverine gauges below warning threshold"
                        onChange={(v) => setToggles({ riverineShowNormal: v })}
                      />
                    </div>
                  ) : (
                    <div className="flex items-center gap-2.5 text-[11px] text-slate-700">
                      <span
                        className="h-3 w-3 shrink-0 rounded-full border border-slate-300/60"
                        style={{ backgroundColor: color }}
                        aria-hidden
                      />
                      <span className="font-medium">{label}</span>
                    </div>
                  )}
                </li>
              ))}
            </ul>
          </div>
        ) : null}
        {toggles.gauges ? (
          <section
            className="rounded-lg border border-slate-200/90 bg-slate-100/90 px-3 py-2.5 shadow-inner"
            aria-label="Extended coverage"
          >
            <div className="flex items-center gap-1.5">
              <p className="text-[11px] font-bold text-slate-900">Extended coverage</p>
              <CustomTooltip content={RIVERINE_LOWER_CONFIDENCE_HELP} multiline position="top">
                <Info className="h-3.5 w-3.5 text-slate-500" strokeWidth={2} aria-hidden />
              </CustomTooltip>
              <span className="sr-only">{RIVERINE_LOWER_CONFIDENCE_HELP}</span>
            </div>
            <div className="mt-2 flex items-center justify-between gap-2">
              <span
                id={lowerConfidenceLabelId}
                className="min-w-0 flex-1 text-[11px] font-medium text-slate-700"
              >
                Lower-confidence gauges only
              </span>
              <FloodHubOverlaySwitch
                checked={!!toggles.riverineLowerConfidenceOnly}
                labelledBy={lowerConfidenceLabelId}
                trackAnalytics={false}
                onChange={handleLowerConfidenceChange}
              />
            </div>
          </section>
        ) : null}
      </div>
      <LowerConfidenceGaugesDisclaimerDialog
        open={showLowerConfidenceDisclaimer}
        onCancel={handleDisclaimerCancel}
        onAccept={handleDisclaimerAccept}
      />
    </div>
  );
}

FloodHubRiverineSection.propTypes = {
  toggles: PropTypes.object.isRequired,
  setToggles: PropTypes.func.isRequired,
};
